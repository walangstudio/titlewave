import { cpSync, mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';

const root = resolve(import.meta.dirname, '..');
const home = mkdtempSync(join(tmpdir(), 'titlewave-packages-'));
const env = { ...process.env, HOME: home, USERPROFILE: home, CODEX_HOME: join(home, '.codex'), CLAUDE_CONFIG_DIR: join(home, '.claude'), GEMINI_CLI_HOME: home, PI_CODING_AGENT_DIR: join(home, '.pi'), PI_OFFLINE: '1' };
delete env.CLAUDECODE;
mkdirSync(env.CODEX_HOME);
const catalog = join(home, 'catalog');
const plugin = join(catalog, 'plugin'); mkdirSync(plugin, { recursive: true });
for (const path of ['.claude-plugin', '.codex-plugin', 'bin', 'lib', 'skills', 'hooks', 'README.md', 'package.json']) cpSync(join(root, path), join(plugin, path), { recursive: true });
mkdirSync(join(catalog, '.claude-plugin'));
writeFileSync(join(catalog, '.claude-plugin/marketplace.json'), JSON.stringify({ name: 'titlewave-test', owner: { name: 'walangstudio' }, plugins: [{ name: 'titlewave', source: './plugin' }] }));
mkdirSync(join(catalog, '.agents/plugins'), { recursive: true });
writeFileSync(join(catalog, '.agents/plugins/marketplace.json'), JSON.stringify({ name: 'titlewave-test', interface: { displayName: 'Titlewave test' }, plugins: [{ name: 'titlewave', source: { source: 'local', path: './plugin' }, policy: { installation: 'AVAILABLE', authentication: 'ON_USE' }, category: 'Productivity' }] }));
const run = (exe, args, combined = false) => {
  const result = spawnSync(exe, args, { env, cwd: root, encoding: 'utf8', timeout: 60000, windowsHide: true });
  assert.equal(result.status, 0, `${exe}: ${result.error || result.stderr || result.stdout}`);
  return combined ? result.stdout + result.stderr : result.stdout;
};
run('claude', ['plugin', 'validate', root]);
run('claude', ['plugin', 'marketplace', 'add', catalog]);
run('claude', ['plugin', 'install', 'titlewave@titlewave-test']);
assert.match(run('claude', ['plugin', 'list']), /titlewave@titlewave-test/);
console.log('PASS Claude marketplace install');
run('codex', ['plugin', 'marketplace', 'add', catalog]);
const installed = JSON.parse(run('codex', ['plugin', 'add', 'titlewave@titlewave-test', '--json']));
assert.equal(installed.name, 'titlewave');
assert.match(run(process.execPath, [join(installed.installedPath, 'bin/titlewave.mjs'), '--help']), /titlewave/);
assert.match(run(process.execPath, [join(installed.installedPath, 'skills/titlewave/scripts/titlewave.mjs'), '--help']), /titlewave/);
console.log('PASS Codex marketplace install with bundled runtime');
run('gemini', ['extensions', 'link', root, '--consent']);
assert.match(run('gemini', ['extensions', 'list'], true), /titlewave/);
console.log('PASS Gemini extension link');
run('pi', ['install', root]);
assert.ok(run('pi', ['list']).includes(root));
console.log('PASS Pi package install');
